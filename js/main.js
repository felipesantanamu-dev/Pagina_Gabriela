function leer(clave) { try { return localStorage.getItem(clave); } catch (e) { return null; } }
function guardar(clave, valor) { try { localStorage.setItem(clave, valor); } catch (e) { /* sin almacenamiento: no se recuerda */ } }

// Por defecto: español y modo día. Solo cambia si la persona lo eligió antes.
let idioma = leer('gc-idioma') === 'en' ? 'en' : 'es';
let tema = leer('gc-tema') === 'oscuro' ? 'oscuro' : 'claro';

// Traduce un texto escrito en español (si el idioma actual es inglés)
function tr(texto) { return idioma === 'en' && ES_EN[texto] ? ES_EN[texto] : texto; }

// --- Traducción de la página ---
const textoOriginal = new WeakMap();
const atributoOriginal = new WeakMap();
const ATRIBUTOS = ['aria-label', 'alt', 'aria-roledescription', 'title'];

function aplicarIdioma() {
  document.documentElement.lang = idioma;

  // Textos
  const recorrido = document.createTreeWalker(document.documentElement, NodeFilter.SHOW_TEXT, {
    acceptNode(nodo) {
      const padre = nodo.parentElement;
      if (!padre || padre.closest('script, style, [data-no-trad]')) return NodeFilter.FILTER_REJECT;
      return nodo.nodeValue.trim() ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT;
    }
  });
  const nodos = [];
  while (recorrido.nextNode()) nodos.push(recorrido.currentNode);
  nodos.forEach((nodo) => {
    if (!textoOriginal.has(nodo)) textoOriginal.set(nodo, nodo.nodeValue);
    const original = textoOriginal.get(nodo);
    const limpio = original.trim();
    const nuevo = idioma === 'en' && ES_EN[limpio] ? original.replace(limpio, ES_EN[limpio]) : original;
    if (nodo.nodeValue !== nuevo) nodo.nodeValue = nuevo;
  });

  // Atributos (etiquetas para lectores de pantalla, textos de las imágenes)
  document.querySelectorAll('[aria-label], [alt], [aria-roledescription], [title]').forEach((el) => {
    if (el.closest('[data-no-trad]')) return;
    if (!atributoOriginal.has(el)) atributoOriginal.set(el, {});
    const guardados = atributoOriginal.get(el);
    ATRIBUTOS.forEach((atributo) => {
      if (!el.hasAttribute(atributo)) return;
      if (!(atributo in guardados)) guardados[atributo] = el.getAttribute(atributo);
      const original = guardados[atributo];
      el.setAttribute(atributo, idioma === 'en' && ES_EN[original] ? ES_EN[original] : original);
    });
  });

  // Descripción de la página
  const meta = document.querySelector('meta[name="description"]');
  if (meta) {
    if (!meta.dataset.es) meta.dataset.es = meta.content;
    meta.content = idioma === 'en' && ES_EN[meta.dataset.es] ? ES_EN[meta.dataset.es] : meta.dataset.es;
  }

  // Enlaces de WhatsApp: el mensaje inicial sigue el idioma
  document.querySelectorAll('a[data-wa]').forEach((a) => {
    a.href = 'https://wa.me/56974262295?text=' + encodeURIComponent(MENSAJE_WHATSAPP[idioma]);
  });

  actualizarHerramientas();
  if (typeof actualizarBotonPausa === 'function') actualizarBotonPausa();
}

// --- Modo día / noche ---
function aplicarTema() {
  if (tema === 'oscuro') document.documentElement.setAttribute('data-tema', 'oscuro');
  else document.documentElement.removeAttribute('data-tema');
  const meta = document.querySelector('meta[name="theme-color"]');
  if (meta) meta.content = tema === 'oscuro' ? '#0a1a26' : '#0f2a3d';
  actualizarHerramientas();
}

// --- Botones de idioma y de modo (sus textos dependen del estado) ---
const botonIdioma = document.querySelector('.boton-idioma');
const botonTema = document.querySelector('.boton-tema');

function actualizarHerramientas() {
  const aEspanol = idioma === 'en';
  botonIdioma.querySelector('.idioma-texto').textContent = aEspanol ? 'ES' : 'EN';
  botonIdioma.lang = aEspanol ? 'es' : 'en';
  const etiquetaIdioma = aEspanol ? 'Cambiar a español' : 'Switch to English';
  botonIdioma.setAttribute('aria-label', etiquetaIdioma);
  botonIdioma.title = etiquetaIdioma;

  const oscuro = tema === 'oscuro';
  botonTema.querySelector('.icono-luna').toggleAttribute('hidden', oscuro);
  botonTema.querySelector('.icono-sol').toggleAttribute('hidden', !oscuro);
  const etiquetaTema = oscuro
    ? (idioma === 'en' ? 'Switch to light mode' : 'Activar modo día')
    : (idioma === 'en' ? 'Switch to dark mode' : 'Activar modo noche');
  botonTema.setAttribute('aria-label', etiquetaTema);
  botonTema.title = etiquetaTema;
}

botonIdioma.addEventListener('click', () => {
  idioma = idioma === 'es' ? 'en' : 'es';
  guardar('gc-idioma', idioma);
  aplicarIdioma();
});
botonTema.addEventListener('click', () => {
  tema = tema === 'claro' ? 'oscuro' : 'claro';
  guardar('gc-tema', tema);
  aplicarTema();
});

